// The generated data files match the design's data pages, and the counts the design gives.
import { expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { ACHIEVEMENTS } from "../src/blocks/achievements/data/achievements.gen";
import { AGENTS, FAMILIES } from "../src/blocks/agents/data/agents.gen";
import { KINDS } from "../src/blocks/items/data/kinds.gen";
import { ORDERS } from "../src/blocks/orders/data/orders.gen";
import { LINES } from "../src/blocks/reports/data/lines.gen";
import { TEST_WIRINGS } from "../src/testbuild/wirings.gen";
import { outputs } from "./extract-data";

const root = resolve(import.meta.dir, "..");

test("generated files are what the design pages give (bun run data changes nothing)", () => {
  for (const [rel, text] of Object.entries(outputs)) {
    expect(readFileSync(join(root, rel), "utf8"), rel).toBe(text);
    expect(text.startsWith("// Generated by scripts/extract-data.ts"), rel).toBe(true);
  }
});

test("data counts: 30 orders, 6 families, 18 agents, 12 kinds, 216 lines, 18 achievements, a test wiring line per order", () => {
  expect(ORDERS.length).toBe(30);
  expect(FAMILIES.length).toBe(6);
  expect(AGENTS.length).toBe(18);
  expect(KINDS.length).toBe(12);
  expect(LINES.length).toBe(216);
  expect(ACHIEVEMENTS.length).toBe(18);
  expect(TEST_WIRINGS.map((l) => l.order)).toEqual(ORDERS.map((o) => o.n));
  // One authored line per agent and item kind.
  expect(new Set(LINES.map((l) => `${l.agent}|${l.kind}`)).size).toBe(AGENTS.length * KINDS.length);
  // ORDER-04, derived: hand-written results 90.
  expect(ORDERS.reduce((n, o) => n + o.results.length, 0)).toBe(90);
});
